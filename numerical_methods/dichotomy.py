# метод дихотомії
def dichotomy(a, b, eps, f):
    """
    Знаходить корінь рівняння методом дихотомії (половинного поділу).
    Приймає початковий відрізок [a, b] та похибку eps.
    Повертає знайдений корінь та кількість ітерацій.
    """
    n = 0
    # Цикл виконується, доки довжина відрізка більша за подвійну похибку
    while (b - a) / 2 > eps:
        c = (a + b) / 2
        # Перевіряємо знак функції в серединній точці для вибору підвідрізка
        if (f(a) * f(c) < 0):
            b = c # звужуємо правий кінець
        else:
            a = c # звужуємо лівий кінець                       
        n = n + 1
    return ((a + b) / 2, n)