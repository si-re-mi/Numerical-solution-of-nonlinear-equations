# метод простих ітерацій
def f(x):
    """
    Вихідна функція рівняння f(x) = 0.
    """
    return x**3 + x**2 - 5*x + 2

def phi (x): 
     """
     Допоміжна функція для методу простих ітерацій (нормальна форма x = phi(x)).
     """
     return (x**3 + x**2 + 2) / 5

def phi_prime(x):
    """
    Похідна функції phi(x) для перевірки умови збіжності (|phi'(x)| < 1).
    phi'(x) = (3x^2 + 2x) / 5
    """
    return (3*x**2 + 2*x) / 5

def iteration(a, b, eps):
    """
    Знаходить корінь рівняння методом простих ітерацій.
    Автоматично обирає безпечну початкову точку на відрізку [a, b].
    Повертає знайдений корінь та кількість ітерацій.
    """
    # Автоматичний вибір початкового наближення:
    # Перевіряємо кінці та середину відрізка на виконання умови збіжності |phi'(x)| < 1
    points = [a, (a + b) / 2, b]
    x_old = a  # значення за замовчуванням
    
    for pt in points:
        if abs(phi_prime(pt)) < 1:
            x_old = pt
            break
            
    x_new = phi(x_old)
    n = 1
    while abs(x_new - x_old) > eps:
        x_old = x_new
        x_new = phi(x_old)                     
        n += 1
        # Захист від зациклення, якщо метод розходиться
        if n > 1000:
            break
        
    return (x_new, n)
